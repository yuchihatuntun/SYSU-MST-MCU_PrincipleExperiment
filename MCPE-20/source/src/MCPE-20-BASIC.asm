;=========================================================
; 1. 堆栈段 (STACK)
;=========================================================
STACK   SEGMENT 'STACK'
    ; 定义100个字节的堆栈空间，初始化为0
    ; 这里的 "DUP(0)" 是最标准的写法，兼容性最好
    STA     DB  100 DUP(0)  
STACK   ENDS

;=========================================================
; 2. 数据段 (DATA)
;=========================================================
DATA    SEGMENT 'DATA'
    ; 步进电机正转励磁序列表 (四相八拍)
    STR1    DB 02H, 06H, 04H, 0CH, 08H, 09H, 01H, 03H
    
    ; 步进电机反转励磁序列表
    STR2    DB 03H, 01H, 09H, 08H, 0CH, 04H, 06H, 02H
DATA    ENDS

;=========================================================
; 3. 代码段 (CODE)
;=========================================================
CODE    SEGMENT 'CODE'
    ASSUME CS:CODE, SS:STACK, DS:DATA
    
    ; 端口地址定义
    IOCON   EQU 8006H
    IOA     EQU 8000H
    IOB     EQU 8002H
    IOC     EQU 8004H

START:
    ;-----------------------------------------------------
    ; 初始化段寄存器
    ;-----------------------------------------------------
    MOV AX, DATA
    MOV DS, AX

    MOV AX, STACK
    MOV SS, AX
    
    ;-----------------------------------------------------
    ; 【核心修改点】直接设置栈顶指针 SP = 100
    ; 不要用 LENGTH STA，直接写数字即可解决报错
    ;-----------------------------------------------------
    MOV SP, 100      
    
    ;-----------------------------------------------------
    ; 初始化 8255
    ;-----------------------------------------------------
    MOV AL, 90H         ; 1001 0000 B (A口入，B口出)
    MOV DX, IOCON
    OUT DX, AL
    NOP                 ; 延时等待稳定

;=========================================================
; 主循环：按键扫描
;=========================================================
TEST_BU:
    MOV DX, IOA
    IN  AL, DX          ; 读按键
    
    TEST AL, 01H        ; 检查 Bit 0
    JE MOT1             ; 跳转正转
    TEST AL, 02H        ; 检查 Bit 1
    JE MOT2             ; 跳转反转
    TEST AL, 04H        ; 检查 Bit 2
    JE MOT3             ; 跳转停止
    
    JMP TEST_BU         ; 循环扫描

;=========================================================
; 正转模块
;=========================================================
MOT1:   
    MOV CX, 08H         ; 循环8次 (8拍)
    LEA DI, STR1        ; 指向正转表
    
IOLED1: 
    MOV AL, [DI]        ; 取数据
    MOV DX, IOB
    OUT DX, AL          ; 输出给电机
    
    INC DI              ; 指针+1
    CALL DELAY          ; 延时控制速度
    LOOP IOLED1         ; 循环
    
    ; 每一轮8拍走完后，检查是否有其他指令
    MOV DX, IOA
    IN  AL, DX
    TEST AL, 02H
    JE MOT2 
    TEST AL, 04H
    JE MOT3 
    JMP MOT1            ; 继续正转

;=========================================================
; 反转模块
;=========================================================
MOT2:   
    MOV CX, 08H         ; 循环8次
    LEA DI, STR2        ; 指向反转表
    
IOLED2: 
    MOV AL, [DI]        ; 取数据
    MOV DX, IOB
    OUT DX, AL          ; 输出给电机
    
    INC DI
    CALL DELAY
    LOOP IOLED2
    
    MOV DX, IOA
    IN  AL, DX
    TEST AL, 01H
    JE MOT1 
    TEST AL, 04H
    JE MOT3 
    JMP MOT2            ; 继续反转

;=========================================================
; 停止模块
;=========================================================
MOT3:   
    MOV AL, 0F0H        ; 全灭 (切断线圈电流)
    MOV DX, IOB
    OUT DX, AL  
    JMP TEST_BU         ; 回到主循环

;=========================================================
; 延时子程序
;=========================================================
DELAY:  PUSH CX
    MOV CX, 011H        ; 调整这个数值改变转速
DELAY1: NOP
    NOP
    NOP
    NOP
    LOOP DELAY1
    POP CX
    RET
    
CODE    ENDS
    END START