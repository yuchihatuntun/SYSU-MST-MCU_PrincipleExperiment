CODE SEGMENT 'CODE'
    ASSUME CS:CODE, DS:DATA

;=========================================================
; 端口地址定义
;=========================================================
IOCON   EQU 8006H       ; 8255 控制口地址
IOA     EQU 8000H       ; 8255 A口地址 (连接数码管段选)
IOB     EQU 8002H       ; 8255 B口地址 (本实验未使用)
IOC     EQU 8004H       ; 8255 C口地址 (连接4x4键盘)

START:
    ; 初始化数据段
    MOV AX, DATA
    MOV DS, AX
    LEA DI, TABLE       ; 将数码管字形表的首地址加载到 DI

    ;=========================================================
    ; 初始化 8255 工作方式
    ;=========================================================
    MOV AL, 88H         ; 控制字 1000 1000 B
                        ; D7=1 (方式控制字)
                        ; A口: 方式0, 输出 (用于数码管)
                        ; B口: 方式0, 输入/输出 (不关心)
                        ; C口: 上半部(PC4-PC7)输入, 下半部(PC0-PC3)输出
    MOV DX, IOCON
    OUT DX, AL

KEY4X4:
    ;=========================================================
    ; 第一行扫描 (ROW 0)
    ;=========================================================
    MOV BX, 0           ; BX 用作行计数器，当前是第0行
    MOV DX, IOC
    MOV AL, 0EH         ; 输出 0000 1110 B -> PC0为低电平(选通第0行)
    OUT DX, AL

    ; 连续读取三次，起到简单的硬件消抖或等待信号稳定的作用
    IN AL, DX
    MOV DX, IOC
    IN AL, DX
    MOV DX, IOC
    IN AL, DX

    OR AL, 0FH          ; 将低4位强制置1 (低4位是输出位，我们只关心高4位输入)
    CMP AL, 0FFH        ; 比较是否全为1 (1111 1111)
                        ; 如果高4位全是1，说明该行没有键按下(有上拉电阻)
    JNE K_N_1           ; 如果不等于FFH，说明有键按下，跳转去判断具体哪一列
    
    ;=========================================================
    ; 第二行扫描 (ROW 1)
    ;=========================================================
    INC BX              ; 行计数器 +1 (现在代表第1行)
    MOV DX, IOC
    MOV AL, 0DH         ; 输出 0000 1101 B -> PC1为低电平
    OUT DX, AL
    
    IN AL, DX           ; 读取状态
    MOV DX, IOC
    IN AL, DX
    MOV DX, IOC
    IN AL, DX
    
    OR AL, 0FH          ; 屏蔽低4位
    CMP AL, 0FFH        ; 检查是否有键按下
    JNE K_N_1           ; 有按下则跳转

    ;=========================================================
    ; 第三行扫描 (ROW 2)
    ;=========================================================
    INC BX              ; 行计数器 +1 (现在代表第2行)
    MOV DX, IOC
    MOV AL, 0BH         ; 输出 0000 1011 B -> PC2为低电平
    OUT DX, AL
    
    IN AL, DX
    MOV DX, IOC
    IN AL, DX
    MOV DX, IOC
    IN AL, DX
    
    OR AL, 0FH
    CMP AL, 0FFH
    JNE K_N_1

    ;=========================================================
    ; 第四行扫描 (ROW 3)
    ;=========================================================
    INC BX              ; 行计数器 +1 (现在代表第3行)
    MOV DX, IOC
    MOV AL, 07H         ; 输出 0000 0111 B -> PC3为低电平
    OUT DX, AL
    
    IN AL, DX
    MOV DX, IOC
    IN AL, DX
    MOV DX, IOC
    IN AL, DX
    
    OR AL, 0FH
    CMP AL, 0FFH
    JNE K_N_1
    
    JMP KEY4X4          ; 如果四行扫完都没按键，重新开始循环扫描

;=========================================================
; 列判断跳转区 (判断是哪一列被按下了)
; 此时 AL 中保存的是读取到的端口状态 (例如 1110 1111)
;=========================================================
K_N_1:
    CMP AL, 0EFH        ; 1110 1111 -> PC4为0 -> 第0列
    JNE K_N_2
    MOV AL, 0           ; 列号 = 0
    JMP K_N             ; 去计算键值

K_N_2:
    CMP AL, 0DFH        ; 1101 1111 -> PC5为0 -> 第1列
    JNE K_N_3
    MOV AL, 1           ; 列号 = 1
    JMP K_N

K_N_3:
    CMP AL, 0BFH        ; 1011 1111 -> PC6为0 -> 第2列
    JNE K_N_4
    MOV AL, 2           ; 列号 = 2
    JMP K_N

K_N_4:
    CMP AL, 7FH         ; 0111 1111 -> PC7为0 -> 第3列
    JNE K_N             ; 异常情况处理
    MOV AL, 3           ; 列号 = 3

;=========================================================
; 键值计算与显示
; 公式：键值 = (行号 * 4) + 列号
;=========================================================
K_N:
    ; 此时 BX = 行号 (0-3), AL = 列号 (0-3)
    MOV CL, 2
    SHL BL, CL          ; BL 左移2位，相当于 BL = BL * 4
    ADD AL, BL          ; AL = AL + BL -> 最终键值 (0-15)
    
    MOV BX, 0           ; 清空 BX，准备做查表索引
    MOV BL, AL          ; 将计算出的键值放入 BL
    MOV AL, [DI+BX]     ; 查表：从 TABLE 中取出对应的段码
    
    MOV DX, IOA
    OUT DX, AL          ; 将段码输出到 A口 (显示在数码管)
    
    JMP KEY4X4          ; 处理完毕，返回继续扫描

CODE ENDS

;=========================================================
; 数据段：数码管字形码表 (共阳极或共阴极取决于硬件)
; 根据 0C0H (1100 0000) 对应 '0' 来看，这是共阳极数码管
;=========================================================
DATA SEGMENT 'DATA'
TABLE DB 0C0H, 0F9H, 0A4H, 0B0H ; 0, 1, 2, 3
      DB 99H,  92H,  82H,  0F8H ; 4, 5, 6, 7
      DB 80H,  90H,  88H,  83H  ; 8, 9, A, B
      DB 0C6H, 0A1H, 86H,  8EH  ; C, D, E, F
DATA ENDS

END START