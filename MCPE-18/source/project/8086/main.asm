CODE    SEGMENT 'CODE' 
        ASSUME CS:CODE,DS:DATA
        
IOCON	EQU 8006H
IOA     EQU 8000H
IOB     EQU 8002H
IOC     EQU 8004H

START:  
	MOV AX, DATA   
	MOV DS, AX
                   
	MOV AL,88H 
	MOV DX,IOCON
	OUT DX,AL 
	
	MOV AL,0FFH
	MOV DX,IOA
	OUT DX,AL

	MOV AL,01H
	MOV DX,IOB
	OUT DX,AL
	
KEY4X4:	
	MOV BX,0
	
	MOV DX,IOC
	MOV AL, 0EH
	OUT DX, AL
	
	IN  AL,DX
	MOV DX,IOC
	IN  AL,DX
	MOV DX,IOC
	IN  AL,DX
	
	OR  AL,0FH
	CMP AL,0FFH ; 0EFH,0DFH,0BFH,7FH
	JNE K_N_1 ;不等于转移
	INC BX
	
	MOV DX,IOC
	MOV AL, 0DH
	OUT DX, AL
	
	IN  AL,DX
	MOV DX,IOC
	IN  AL,DX
	MOV DX,IOC	
	IN  AL,DX
	
	OR  AL,0FH
	CMP AL,0FFH ; 0EFH,0DFH,0BFH,7FH
	JNE K_N_1 ;不等于转移
	INC BX
	
	MOV DX,IOC
	MOV AL, 0BH
	OUT DX, AL
	IN  AL,DX
	
	MOV DX,IOC
	IN  AL,DX
	MOV DX,IOC
	
	IN  AL,DX
	OR  AL,0FH
	CMP AL,0FFH ; 0EFH,0DFH,0BFH,7FH
	JNE K_N_1 ;不等于转移
	INC BX
	
	MOV DX,IOC
	MOV AL, 07H
	OUT DX, AL
	
	IN  AL,DX
	MOV DX,IOC
	IN  AL,DX
	MOV DX,IOC
	IN  AL,DX
	
	OR  AL,0FH
	CMP AL,0FFH ; 0EFH,0DFH,0BFH,7FH
	JNE K_N_1 ;不等于转移
	
	JMP KEY4X4

	
K_N_1:
	;按键消抖
	MOV CX,50
	LOOP $
	IN  AL,DX
	OR  AL,0FH
	CMP AL,0FFH ; 0EFH,0DFH,0BFH,7FH
	JZ KEY4X4

	;按键列判断
	CMP AL,0EFH
	JNE K_N_2
	MOV AL,0
	JMP K_N
K_N_2:	CMP AL,0DFH
	JNE K_N_3
	MOV AL,1
	JMP K_N
K_N_3:	CMP AL,0BFH
	JNE K_N_4
	MOV AL,2
	JMP K_N
K_N_4:	CMP AL,7FH
	JNE K_N
	MOV AL,3
	
K_N:	

	MOV CL,2
	SHL BL,CL  
	ADD AL,BL
	MOV BX,OFFSET TABLE
	XLAT
	MOV DX,IOA
	OUT DX,AL
	
	JMP KEY4X4
		
CODE    ENDS
      
DATA    SEGMENT 'DATA'
TABLE 	DB 0C0H,0F9H,0A4H,0B0H,99H,92H,82H,0F8H,80H,90H,88H,83H,0C6H,0A1H,86H,8EH ;0-F
DATA    ENDS
        END START
