;=========================================================
; 1. 堆栈段 (STACK) - 放在最前面以避免编译错误
;=========================================================
STACK   SEGMENT 'STACK'
    STA     DB  100 DUP(0)  ; 分配100字节堆栈空间，初始化为0
STACK   ENDS

;=========================================================
; 2. 数据段 (DATA) - 存放点阵字模
;=========================================================
DATA    SEGMENT 'DATA'
    ; 这里存放了 32 个字节的数据
    ; 每 8 个字节组成一幅画面 (8x8点阵)，这里共有 4 幅画面
    ; 程序会依次显示这 4 组数据，形成简单的动画效果
TABLE   DB  0FFH,0EFH,0D7H,0BBH,0BBH,0ABH,31H,0FBH ; 第1帧
        DB  0FFH,0EFH,0D7H,0BBH,0BBH,0ABH,29H,0EFH ; 第2帧
        DB  0FFH,0EFH,0D7H,0BBH,0BBH,0ABH,19H,0BFH ; 第3帧
        DB  0FFH,0EFH,0D7H,0BBH,0BBH,0ABH,29H,0EFH ; 第4帧
DATA    ENDS

;=========================================================
; 3. 代码段 (CODE)
;=========================================================
CODE    SEGMENT 'CODE'
    ASSUME CS:CODE, SS:STACK, DS:DATA
    
    ; 端口地址定义
    IOCON   EQU 8006H       ; 8255 控制口
    IOA     EQU 8000H       ; A口 (用于行扫描/位选)
    IOB     EQU 8002H       ; B口 (用于输出字形码/段选)
    IOC     EQU 8004H       ; C口 (未使用)

START:
    ;-----------------------------------------------------
    ; 初始化段寄存器
    ;-----------------------------------------------------
    MOV AX, DATA
    MOV DS, AX

    MOV AX, STACK
    MOV SS, AX
    MOV SP, 100         ; 设置栈顶指针
    
    ;-----------------------------------------------------
    ; 8255 初始化
    ;-----------------------------------------------------
TEST_BU:
    MOV AL, 80H         ; 控制字 1000 0000 B
                        ; A口: 方式0, 输出 (控制扫描行)
                        ; B口: 方式0, 输出 (控制显示的LED点)
    MOV DX, IOCON
    OUT DX, AL
    NOP
    
    ;-----------------------------------------------------
    ; 主显示循环
    ;-----------------------------------------------------
DISP:
    LEA DI, TABLE       ; 将 DI 指向字形表的首地址
    MOV CX, 04H         ; 设置外层循环次数：4帧画面

DISP1:  ; --- 外层循环：切换画面 (Frame Loop) ---
    PUSH CX             ; 保存外层计数器 (因为内层也要用CX)
    
    MOV CX, 08H         ; 设置内层循环次数：8行扫描
    MOV BH, 01H         ; 初始化扫描码：0000 0001
                        ; 表示从第1行开始点亮

DISP2:  ; --- 内层循环：行扫描 (Row Scan Loop) ---
    
    ; 步骤1：消隐 (Anti-ghosting)
    ; 在发送新数据前，先关闭所有行，防止上一行的数据“鬼影”显示在当前行
    MOV DX, IOA
    MOV AL, 00H
    OUT DX, AL

    ; 步骤2：输出字形数据 (列数据)
    MOV DX, IOB
    MOV AL, [DI]        ; 从表中取出一个字节数据
    OUT DX, AL          ; 送入 B 口

    ; 步骤3：输出扫描码 (选中当前行)
    MOV DX, IOA
    MOV AL, BH          ; 将当前的行选信号 (如 0000 0001)
    OUT DX, AL          ; 送入 A 口

    ; 步骤4：视觉停留延时
    CALL DELAY2         ; 短延时，让LED亮一小会儿，人眼才能看清

    ; 步骤5：准备下一行
    INC DI              ; 数据指针+1，指向下一行的数据
    
    ; 移位操作：生成下一个扫描码
    MOV AL, BH
    SHL AL, 1           ; 左移一位 (0000 0001 -> 0000 0010)
    MOV BH, AL          ; 保存回 BH，用于下一次循环
    
    LOOP DISP2          ; 循环8次，直到扫完这一帧的8行
    
    POP CX              ; 恢复外层计数器
    LOOP DISP1          ; 循环4次，直到显示完4帧画面
    
    JMP DISP            ; 重新开始，循环播放动画

;=========================================================
; 延时子程序 (长延时 - 未在主逻辑中使用)
;=========================================================
DELAY:  PUSH CX
    MOV CX, 10FH
DELAY1: NOP
    NOP
    NOP
    NOP
    LOOP DELAY1
    POP CX
    RET
    
;=========================================================
; 扫描延时子程序 (短延时 - 关键)
; 用于控制每一行的点亮时间
;=========================================================
DELAY2: PUSH CX
    MOV CX, 01H         ; 延时非常短
DELAY3: NOP
    NOP
    LOOP DELAY3
    POP CX
    RET
    
CODE    ENDS
    END START